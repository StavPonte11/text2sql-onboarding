import re


def clean_sql(query: str) -> str:
    """
    Clean SQL text generated by LLMs.
    
    Removes surrounding Markdown code fences and a trailing semicolon, then trims the result.
    
    Returns:
        str: The cleaned SQL string, or an empty string for falsy input.
    """
    if not query:
        return ""

    cleaned = query.strip()
    cleaned = re.sub(r"^```(?:sql)?\s*", "", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned)

    # Strip trailing semicolon if present
    cleaned = cleaned.strip()
    if cleaned.endswith(";"):
        cleaned = cleaned[:-1].strip()

    return cleaned
